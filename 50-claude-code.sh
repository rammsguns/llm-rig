#!/usr/bin/env bash
# Wire Claude Code to the local stack.
#
# Claude Code speaks the Anthropic Messages API (/v1/messages). Recent
# llama-server builds implement that endpoint natively -- in which case we point
# Claude Code straight at llama-swap and DELETE the translation layer. Fewer
# moving parts, no per-request rewrite, and no risk of a proxy reordering the
# prompt prefix and destroying cache hits.
#
# LiteLLM is only installed if the native endpoint is missing.
set -uo pipefail
source "$(dirname "$0")/lib/detect.sh"
detect_hw

mkdir -p "$RIG_DIR/etc"

MODELS=$(curl -sf "http://127.0.0.1:$LLAMA_PORT/v1/models" | jq -r '.data[].id' 2>/dev/null)
[[ -n "$MODELS" ]] || die "llama-swap not responding on $LLAMA_PORT. Run ./40-serve.sh first."
c_info "Models available:"; echo "$MODELS" | sed 's/^/    /' >&2

# Prefer the MoE coder as primary; smallest as the cheap/background model.
PRIMARY=$(echo "$MODELS" | grep -i 'coder' | head -1)
[[ -n "$PRIMARY" ]] || PRIMARY=$(echo "$MODELS" | head -1)
FAST=$(echo "$MODELS" | grep -iv "^$PRIMARY$" | head -1)
[[ -n "$FAST" ]] || FAST="$PRIMARY"

# --- does the backend already speak Anthropic? ------------------------------
probe_messages() {
  local port="$1"
  local code
  code=$(curl -s -o /tmp/.llmrig_probe -w '%{http_code}' --max-time 600 \
    -X POST "http://127.0.0.1:$port/v1/messages" \
    -H 'content-type: application/json' \
    -H 'anthropic-version: 2023-06-01' \
    -H 'x-api-key: local' \
    -d "{\"model\":\"$PRIMARY\",\"max_tokens\":16,\"messages\":[{\"role\":\"user\",\"content\":\"say hi\"}]}" \
    2>/dev/null)
  # A 200 with a content block means native support. 404 means no such route.
  [[ "$code" == 200 ]] && jq -e '.content' /tmp/.llmrig_probe >/dev/null 2>&1
}

c_info "Probing for a native /v1/messages endpoint (first call loads the model, be patient)"
if probe_messages "$LLAMA_PORT"; then
  NATIVE=1
  TARGET_PORT="$LLAMA_PORT"
  c_ok "llama-server speaks Anthropic natively -- SKIPPING LiteLLM entirely"
  c_info "One less hop, and nothing rewrites your prompt prefix between requests."
  sudo systemctl disable --now litellm.service 2>/dev/null || true
else
  NATIVE=0
  TARGET_PORT="$PROXY_PORT"
  c_warn "No native /v1/messages -- installing LiteLLM as a translation layer"
fi

# --- LiteLLM, only if needed ------------------------------------------------
if (( ! NATIVE )); then
  if ! need litellm; then
    c_info "Installing LiteLLM"
    pip install --user --break-system-packages -q "litellm[proxy]" || die "pip install failed"
    hash -r
  fi

  # Version reporting is INFORMATIONAL. v2 died here on a healthy install
  # because modern litellm has no top-level __version__ -- the version lives in
  # package metadata. Health is "does it import and is the CLI on PATH", nothing more.
  LITELLM_VER=$(python3 - <<'PY' 2>/dev/null
import sys
v = None
try:
    from importlib.metadata import version
    v = version("litellm")
except Exception:
    try:
        import litellm
        v = getattr(litellm, "__version__", None)
    except Exception:
        sys.exit(1)
print(v or "unknown")
PY
)
  if [[ -z "$LITELLM_VER" ]]; then
    python3 -c 'import litellm' 2>/dev/null \
      || die "litellm will not import. Try:
     pip install --user --break-system-packages --force-reinstall 'litellm[proxy]'"
    LITELLM_VER="unknown"
  fi
  need litellm || die "litellm not on PATH. Run ./05-path-fix.sh && source ~/.bashrc"
  c_ok "litellm $LITELLM_VER at $(command -v litellm)"

  CFG="$RIG_DIR/etc/litellm.yaml"
  c_info "Generating $CFG"
  {
  echo "# Generated by llm-rig 50-claude-code.sh"
  echo "model_list:"
  while IFS= read -r m; do
    printf '  - model_name: %s\n' "$m"
    printf '    litellm_params:\n'
    printf '      model: openai/%s\n' "$m"
    printf '      api_base: http://127.0.0.1:%s/v1\n' "$LLAMA_PORT"
    printf '      api_key: none\n'
    printf '      drop_params: true\n'
  done <<< "$MODELS"
  cat <<EOF

litellm_settings:
  request_timeout: 1200
  num_retries: 1
  telemetry: false
EOF
  } > "$CFG"

  sudo tee /etc/systemd/system/litellm.service >/dev/null <<EOF
[Unit]
Description=LiteLLM proxy (Anthropic Messages API -> llama-swap)
After=network-online.target llama-swap.service
Wants=llama-swap.service

[Service]
Type=simple
User=$USER
Environment=PATH=$HOME/.local/bin:/usr/local/bin:/usr/bin:/bin
ExecStart=$HOME/.local/bin/litellm --config $CFG --host 0.0.0.0 --port $PROXY_PORT
Restart=on-failure
RestartSec=5

[Install]
WantedBy=multi-user.target
EOF
  sudo systemctl daemon-reload
  sudo systemctl enable litellm.service >/dev/null 2>&1
  sudo systemctl restart litellm.service
  sleep 6
  systemctl is-active --quiet litellm && c_ok "litellm running on $PROXY_PORT" \
    || { sudo journalctl -u litellm -n 30 --no-pager >&2; die "litellm failed to start"; }
fi

# --- Claude Code env -------------------------------------------------------
ENVF="$RIG_DIR/claude-code-local.env"
LAN_IP=$(hostname -I | awk '{print $1}')
cat > "$ENVF" <<EOF
# Generated by llm-rig. Source this before running claude.
# Path: Claude Code -> $( ((NATIVE)) && echo "llama-swap (native Anthropic API)" || echo "LiteLLM -> llama-swap" )
export ANTHROPIC_BASE_URL="http://127.0.0.1:$TARGET_PORT"
export ANTHROPIC_AUTH_TOKEN="local"

# Claude Code requests opus/sonnet/haiku; map them onto what we actually serve.
export ANTHROPIC_DEFAULT_OPUS_MODEL="$PRIMARY"
export ANTHROPIC_DEFAULT_SONNET_MODEL="$PRIMARY"
export ANTHROPIC_DEFAULT_HAIKU_MODEL="$FAST"

export CLAUDE_CODE_MAX_OUTPUT_TOKENS=8192

# Local models handle the small background tasks poorly; disabling them saves
# tokens and avoids polluting the KV cache prefix we want to keep warm.
export DISABLE_NON_ESSENTIAL_MODEL_CALLS=1
export DISABLE_TELEMETRY=1

# From another machine on the LAN:
# export ANTHROPIC_BASE_URL="http://$LAN_IP:$TARGET_PORT"
EOF
c_ok "$ENVF"

# --- the test that actually matters ----------------------------------------
echo >&2
c_info "Asserting tool calling works (this is what makes or breaks Claude Code)"
resp=$(curl -sf --max-time 600 -X POST "http://127.0.0.1:$TARGET_PORT/v1/messages" \
  -H 'content-type: application/json' \
  -H 'anthropic-version: 2023-06-01' \
  -H 'x-api-key: local' \
  -d "{
    \"model\": \"$PRIMARY\",
    \"max_tokens\": 256,
    \"tools\": [{
      \"name\": \"read_file\",
      \"description\": \"Read a file from disk\",
      \"input_schema\": {\"type\":\"object\",\"properties\":{\"path\":{\"type\":\"string\"}},\"required\":[\"path\"]}
    }],
    \"messages\": [{\"role\":\"user\",\"content\":\"Read the file /etc/hostname using the read_file tool.\"}]
  }" 2>&1)

if echo "$resp" | jq -e '.content[]? | select(.type=="tool_use")' >/dev/null 2>&1; then
  c_ok "TOOL CALLING WORKS"
  echo "$resp" | jq -c '.content[] | select(.type=="tool_use")' | sed 's/^/    /' >&2
  echo >&2
  c_info "Ready. Run:  source $ENVF && claude"
else
  c_err "No tool_use block returned -- Claude Code will not be able to edit files."
  echo "$resp" | head -30 | sed 's/^/    /' >&2
  c_warn "Check, in order:
     1. --jinja present in $RIG_DIR/etc/llama-swap.yaml   (most common cause)
     2. the GGUF ships a chat template with tool support:
          llama-server --help | grep -i chat-template
     3. try the other model: PRIMARY override, e.g. devstral is tuned for this"
fi

echo >&2
c_info "Path: Claude Code -> :$TARGET_PORT $( ((NATIVE)) && echo '(llama-swap, native)' || echo '(LiteLLM -> llama-swap)' )"
c_info "LAN:  http://$LAN_IP:$TARGET_PORT"
