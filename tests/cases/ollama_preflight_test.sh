}

test_tool_call_check_rejects_text_only_response() {
  # The heart of issue #1: a valid, healthy-looking answer with no tool_use.
  load_preflight
  mock_route_file POST "/v1/messages" 200 "$API/messages_text_only.json"
  run preflight_check_tool_call "http://127.0.0.1:8081" "some-model"
  assert_fails "text-only response must not pass"
}

test_tool_call_check_accepts_tool_use_response() {
  load_preflight
  mock_route_file POST "/v1/messages" 200 "$API/messages_tool_use.json"
  run preflight_check_tool_call "http://127.0.0.1:8081" "some-model"
  assert_ok "tool_use response must pass"
}

# --- full script: fail-closed guarantees ------------------------------------

test_active_service_with_zero_models_does_not_remove_ollama() {
  # llama-swap is active, which is all the OLD guard checked.
  write_env "http://127.0.0.1:8081"
  mock_route_file GET "/v1/models" 200 "$API/models_empty.json"
  run_removal
  assert_fails "removal must abort" || return 1
  assert_contains "$RUN_OUTPUT" "Preflight FAILED" "diagnostic" || return 1
  assert_no_destructive_calls
}

test_text_only_model_does_not_remove_ollama() {
  write_env "http://127.0.0.1:8081"
  mock_route_file GET  "/v1/models"   200 "$API/models_ok.json"
  mock_route_file POST "/v1/messages" 200 "$API/messages_text_only.json"
  run_removal
  assert_fails "removal must abort" || return 1
  assert_contains "$RUN_OUTPUT" "tool_use" "diagnostic names the failure" || return 1
  assert_no_destructive_calls
}

test_unreachable_endpoint_does_not_remove_ollama() {
  write_env "http://127.0.0.1:8081"
  run_removal
  assert_fails "removal must abort" || return 1
  assert_no_destructive_calls
}

test_model_that_fails_to_load_does_not_remove_ollama() {
  write_env "http://127.0.0.1:8081"
  mock_route_file GET  "/v1/models"   200 "$API/models_ok.json"
  mock_route_file POST "/v1/messages" 500 "$API/error_500.json"
  run_removal
  assert_fails "removal must abort" || return 1
  assert_no_destructive_calls
}

test_litellm_configuration_is_probed_on_its_own_port() {
  # A healthy stack on :4000 must be found there. If the script still probed
  # PROXY_PORT unconditionally -- or LLAMA_PORT unconditionally -- one of these
  # two tests fails.
  write_env "http://127.0.0.1:4000"
  route_healthy_stack "http://127.0.0.1:4000"
  run bash -c "printf 'n\n' | bash '$REPO_ROOT/90-remove-ollama.sh'"
  assert_contains "$RUN_OUTPUT" "127.0.0.1:4000" "probed endpoint" || return 1
  assert_not_contains "$RUN_OUTPUT" "Preflight FAILED" "preflight should pass"
}

test_native_configuration_is_probed_on_its_own_port() {
  write_env "http://127.0.0.1:8081"
  route_healthy_stack "http://127.0.0.1:8081"
  run bash -c "printf 'n\n' | bash '$REPO_ROOT/90-remove-ollama.sh'"
  assert_contains "$RUN_OUTPUT" "127.0.0.1:8081" "probed endpoint" || return 1
  assert_not_contains "$RUN_OUTPUT" "Preflight FAILED" "preflight should pass"
}

test_declining_the_prompt_removes_nothing() {
  write_env "http://127.0.0.1:8081"
  route_healthy_stack "http://127.0.0.1:8081"
  run bash -c "printf 'n\n' | bash '$REPO_ROOT/90-remove-ollama.sh'"
  assert_contains "$RUN_OUTPUT" "aborted" "abort message" || return 1
  assert_no_destructive_calls
}

# --- negative control -------------------------------------------------------

test_healthy_stack_does_proceed_to_removal() {
  # Without this, every "no destructive calls" assertion above could be passing
  # for the wrong reason -- e.g. a typo'd assertion pattern that never matches.
  # This proves the detector fires when removal really happens.
  write_env "http://127.0.0.1:8081"
  route_healthy_stack "http://127.0.0.1:8081"
  export MOCK_DPKG_OLLAMA=1
  run_removal
  assert_ok "healthy stack should allow removal" || return 1
  assert_called 'apt-get remove' "ollama package removal"
}

# --- FORCE escape hatch -----------------------------------------------------

test_force_overrides_a_failed_preflight() {
  write_env "http://127.0.0.1:8081"
  mock_route_file GET "/v1/models" 200 "$API/models_empty.json"
  export FORCE=1 MOCK_DPKG_OLLAMA=1
  run_removal
  assert_ok "FORCE=1 should proceed" || return 1
  assert_called 'apt-get remove' "removal proceeded under FORCE"
}

test_force_warns_prominently_before_proceeding() {
  write_env "http://127.0.0.1:8081"
  mock_route_file GET "/v1/models" 200 "$API/models_empty.json"
  export FORCE=1
  run_removal
  assert_contains "$RUN_OUTPUT" "NO working local model" "FORCE warning"
}

run_suite
suite_exit
